const text = value => typeof value === 'string' && value.trim() ? value : '';

function languageCode(language) {
  const code = typeof language === 'string' ? language.trim().toLowerCase().split(/[-_]/)[0] : '';
  return Object.hasOwn(TRANSLATIONS, code) ? code : 'en';
}

export function localize(language, key) {
  if (typeof key !== 'string') return '';
  const catalogue = TRANSLATIONS[languageCode(language)];
  if (Object.hasOwn(catalogue, key)) return catalogue[key];
  return Object.hasOwn(TRANSLATIONS.en, key) ? TRANSLATIONS.en[key] : key;
}

export function metadataView(state, language = 'en') {
  const available = Boolean(state && !['unknown', 'unavailable'].includes(state.state));
  const a = available ? state.attributes || {} : {};
  const event = a.audio_event_active === true;
  const album = event ? '' : text(a.media_album_name);
  const eventKey = 'event_' + text(a.audio_event);
  const reportedSource = text(a.source);
  const sourceKey = {'Local Library': 'source_local_library', 'Line-In': 'source_line_in'};
  const source = event
    ? localize(language, Object.hasOwn(TRANSLATIONS.en, eventKey) ? eventKey : 'interruption')
    : Object.hasOwn(sourceKey, reportedSource) ? localize(language, sourceKey[reportedSource]) : reportedSource;
  return {
    available,
    title: text(a.media_title) || localize(language, 'missing_title'),
    artist: event ? '' : text(a.media_artist),
    album,
    source: source || localize(language, 'not_reported'),
  };
}

export function controlRequest(entity, action, value, language = 'en') {
  if (typeof entity !== 'string' || !/^media_player\.[a-z0-9_]+$/.test(entity)) {
    throw new Error(localize(language, 'invalid_entity'));
  }
  const services = {play: 'media_play', pause: 'media_pause', previous: 'media_previous_track', next: 'media_next_track', volume: 'volume_set'};
  if (!Object.hasOwn(services, action)) throw new Error(localize(language, 'unsupported_action'));
  const data = {entity_id: entity};
  if (action === 'volume') {
    if (typeof value !== 'number' || !Number.isFinite(value) || value < 0 || value > 1) {
      throw new Error(localize(language, 'invalid_volume'));
    }
    data.volume_level = value;
  }
  return {domain: 'media_player', service: services[action], data};
}

export function safeArtwork(value, base) {
  if (!text(value)) return null;
  try {
    const origin = new URL(base);
    const url = new URL(value, origin);
    return ['http:', 'https:'].includes(url.protocol) && url.origin === origin.origin && !url.username && !url.password ? url.href : null;
  } catch {
    return null;
  }
}

